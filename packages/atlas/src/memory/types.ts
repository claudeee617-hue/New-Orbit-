import { isSafeRepoRelativePath, normalizeRepoRelativePath } from '@orbit/shared';
import { z } from 'zod';

/** What a memory item is about. The first five are normative ("we decided / we require"). */
export const MEMORY_CATEGORIES = [
  'architecture-decision',
  'design-constraint',
  'api-contract',
  'team-convention',
  'build-requirement',
  // Descriptive: facts about what happened or what was found.
  'known-bug',
  'historical-fix',
  'repository-discovery',
] as const;
export type MemoryCategory = (typeof MEMORY_CATEGORIES)[number];

/** Normative categories are stored as `Decision` nodes, descriptive ones as `Documentation`. */
export const NORMATIVE_CATEGORIES: ReadonlySet<MemoryCategory> = new Set([
  'architecture-decision',
  'design-constraint',
  'api-contract',
  'team-convention',
  'build-requirement',
]);

/**
 * Who stands behind the statement.
 * - human: a person wrote it (or confirmed an AI suggestion).
 * - imported: read verbatim from a repository document such as an ADR.
 * - ai-suggested: generated by an AI. NEVER authoritative until a person confirms it.
 */
export const MEMORY_AUTHORITIES = ['human', 'imported', 'ai-suggested'] as const;
export type MemoryAuthority = (typeof MEMORY_AUTHORITIES)[number];

export const MEMORY_STATUSES = ['active', 'invalidated'] as const;
export type MemoryStatus = (typeof MEMORY_STATUSES)[number];

export const DECISION_STATUSES = [
  'proposed',
  'accepted',
  'deprecated',
  'superseded',
  'rejected',
  'unknown',
] as const;
export type DecisionStatus = (typeof DECISION_STATUSES)[number];

export const MEMORY_LIMITS = {
  maxTitle: 200,
  maxBody: 8000,
  maxTags: 20,
  maxTag: 40,
  maxSourceRefs: 30,
  maxReason: 500,
  maxResults: 100,
  defaultResults: 20,
} as const;

const sha256 = z.string().regex(/^[0-9a-f]{64}$/, 'must be a lowercase SHA-256 hex digest');
const repoPath = z
  .string()
  .min(1)
  .max(1024)
  .refine(isSafeRepoRelativePath, 'must be a relative path inside the repository')
  .transform(normalizeRepoRelativePath);

/** A pointer to where a statement comes from. File refs may record the hash they were read at. */
export const sourceRefSchema = z.discriminatedUnion('kind', [
  z.strictObject({
    kind: z.literal('file'),
    path: repoPath,
    startLine: z.number().int().min(1).optional(),
    endLine: z.number().int().min(1).optional(),
    /** SHA-256 of the file when the memory was written. Used for staleness detection. */
    contentHash: sha256.optional(),
  }),
  z.strictObject({
    kind: z.literal('commit'),
    sha: z
      .string()
      .regex(/^[0-9a-fA-F]{7,64}$/)
      .transform((v) => v.toLowerCase()),
  }),
  z.strictObject({ kind: z.literal('pull-request'), number: z.number().int().min(1) }),
  z.strictObject({ kind: z.literal('issue'), number: z.number().int().min(1) }),
  z.strictObject({
    kind: z.literal('url'),
    url: z
      .url()
      .max(2000)
      .refine((v) => /^https?:\/\//i.test(v), 'must be http(s)'),
  }),
]);
export type SourceRef = z.output<typeof sourceRefSchema>;

const cleanText = (max: number) =>
  z
    .string()
    .trim()
    .min(1)
    .max(max)
    // eslint-disable-next-line no-control-regex
    .refine((v) => !/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/.test(v), {
      message: 'must not contain control characters',
    });

const tag = z
  .string()
  .trim()
  .toLowerCase()
  .regex(/^[a-z0-9][a-z0-9._:/-]*$/, 'tags are lowercase letters, digits and . _ : / -')
  .max(MEMORY_LIMITS.maxTag);

export const memoryCreateSchema = z.strictObject({
  category: z.enum(MEMORY_CATEGORIES),
  title: cleanText(MEMORY_LIMITS.maxTitle),
  body: cleanText(MEMORY_LIMITS.maxBody),
  /** Stable id fragment. Defaults to a slug of the title. */
  slug: z
    .string()
    .regex(/^[a-z0-9][a-z0-9-]{0,79}$/)
    .optional(),
  tags: z.array(tag).max(MEMORY_LIMITS.maxTags).default([]),
  /** Structured decision fields enable exact conflict detection ("database" -> "sqlite"). */
  topic: tag.optional(),
  choice: cleanText(120).optional(),
  sourceRefs: z.array(sourceRefSchema).max(MEMORY_LIMITS.maxSourceRefs).default([]),
  /** human (default) or ai-suggested. `imported` is reserved for the importers. */
  authority: z.enum(['human', 'ai-suggested']).default('human'),
  /** Who is recording this: a name or handle. No email addresses are stored. */
  createdBy: cleanText(80).refine((v) => !v.includes('@') || v.startsWith('ai:'), {
    message: 'use a name or handle, not an email address',
  }),
});
export type MemoryCreateInput = z.input<typeof memoryCreateSchema>;

export const memoryUpdateSchema = z
  .strictObject({
    title: cleanText(MEMORY_LIMITS.maxTitle).optional(),
    body: cleanText(MEMORY_LIMITS.maxBody).optional(),
    tags: z.array(tag).max(MEMORY_LIMITS.maxTags).optional(),
    topic: tag.optional(),
    choice: cleanText(120).optional(),
    sourceRefs: z.array(sourceRefSchema).max(MEMORY_LIMITS.maxSourceRefs).optional(),
    /** Why the change was made. Required: history should explain itself. */
    reason: cleanText(MEMORY_LIMITS.maxReason),
    updatedBy: cleanText(80),
  })
  .refine(
    (v) =>
      v.title !== undefined ||
      v.body !== undefined ||
      v.tags !== undefined ||
      v.topic !== undefined ||
      v.choice !== undefined ||
      v.sourceRefs !== undefined,
    { message: 'nothing to update' },
  );
export type MemoryUpdateInput = z.input<typeof memoryUpdateSchema>;

export const memoryInvalidateSchema = z.strictObject({
  reason: cleanText(MEMORY_LIMITS.maxReason),
  invalidatedBy: cleanText(80),
  /** The memory id that replaces this one, if any. Creates a SUPERSEDES link. */
  supersededBy: z.string().min(1).max(200).optional(),
});
export type MemoryInvalidateInput = z.input<typeof memoryInvalidateSchema>;

export const memoryConfirmSchema = z.strictObject({
  confirmedBy: cleanText(80).refine((v) => !v.startsWith('ai:'), {
    message: 'only a person can confirm an AI suggestion',
  }),
  note: cleanText(MEMORY_LIMITS.maxReason).optional(),
});
export type MemoryConfirmInput = z.input<typeof memoryConfirmSchema>;

export interface MemoryItem {
  /** Stable, human-readable id: `memory/<category>/<slug>`. */
  id: string;
  nodeId: string;
  category: MemoryCategory;
  title: string;
  body: string;
  tags: string[];
  topic?: string;
  choice?: string;
  authority: MemoryAuthority;
  status: MemoryStatus;
  /** True only when a person (or a verbatim repository document) stands behind it and it is active. */
  authoritative: boolean;
  decisionStatus?: DecisionStatus;
  adrNumber?: number;
  sourceRefs: SourceRef[];
  version: number;
  createdBy: string;
  changeReason?: string;
  invalidation?: { reason: string; by: string };
  confirmation?: { by: string; note?: string };
  /** True when `body` is an excerpt of a longer document. */
  excerpt: boolean;
  importedFrom?: string;
  /** Memory ids this item supersedes / is superseded by (SUPERSEDES edges). */
  supersedes: string[];
  supersededBy: string[];
  evidenceId: string;
  recordedAt: string;
}

export interface MemoryVersion {
  version: number;
  item: MemoryItem;
  /** Evidence record that supports this version. */
  evidenceId: string;
  recordedAt: string;
  deleted: boolean;
}
